#!/usr/bin/env python3
"""Evaluate our detector/decoder against a synthetic dataset.

Reads a dataset directory (images/ + metadata.jsonl) generated by
``generate_dataset.py`` and reports detection rate, decode rate, version
accuracy, corner error, and timing.

Usage:
    python src/qr_reader/scripts/eval_dataset.py \\
        --dataset-dir data/synth \\
        --num-samples 100
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from time import perf_counter
from typing import Any

import cv2
import numpy as np

from qr_reader.decoder.decoder import decode
from qr_reader.detector.detector import detect_corners, detect_homography, compute_qr_corners
from qr_reader.detector.sample import sample_qr_bits


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Evaluate QR detector/decoder on a synthetic dataset."
    )
    parser.add_argument(
        "--dataset-dir",
        required=True,
        type=Path,
        help="Directory containing images/ and metadata.jsonl",
    )
    parser.add_argument(
        "--num-samples",
        type=int,
        default=0,
        help="Max samples to evaluate (0 = all).",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=0,
        help="Random seed for sample subset selection.",
    )
    return parser


def load_dataset(dataset_dir: Path, num_samples: int = 0, seed: int = 0) -> list[dict]:
    meta_path = dataset_dir / "metadata.jsonl"
    if not meta_path.is_file():
        raise FileNotFoundError(f"Metadata not found: {meta_path}")

    with open(meta_path) as f:
        records = [json.loads(line) for line in f]

    if num_samples > 0 and num_samples < len(records):
        rng = np.random.default_rng(seed)
        indices = rng.choice(len(records), size=num_samples, replace=False)
        records = [records[i] for i in sorted(indices)]

    return records


def evaluate_sample(rec: dict, dataset_dir: Path) -> dict[str, Any]:
    img_path = dataset_dir / "images" / f"{rec['sample_index']:06d}.jpg"
    image = cv2.imread(str(img_path))
    if image is None:
        return {"error": "image_not_found", "detect_ok": False, "decode_ok": False}

    image_gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

    result: dict[str, Any] = {"detect_ok": False, "decode_ok": False}

    t0 = perf_counter()

    try:
        H, version_det = detect_homography(image_gray)
        result["detect_ok"] = True
        result["version_det"] = version_det
        N_det = 4 * version_det + 17
        result["N_det"] = N_det

        corners_det = compute_qr_corners(H, N_det)
        result["corners_det"] = corners_det.tolist()

        corners_gt = rec["corners_qr"]
        gt_arr = np.array(
            [corners_gt["TL"], corners_gt["TR"], corners_gt["BR"], corners_gt["BL"]],
            dtype=np.float64,
        )
        result["corners_gt_xy"] = corners_gt

        errors = np.linalg.norm(corners_det - gt_arr, axis=1)
        N_gt = rec["N"]
        ppm = rec["pixels_per_module"]
        module_size = N_gt / N_det * ppm if N_det else ppm
        result["corner_rmse"] = float(np.sqrt(np.mean(errors ** 2)))
        result["corner_rmse_norm"] = float(
            result["corner_rmse"] / max(module_size, 1e-6)
        )

        version_gt = rec["version"]
        result["version_gt"] = version_gt
        result["version_ok"] = version_det == version_gt
    except ValueError as e:
        result["error"] = str(e)
    except Exception as e:
        result["error"] = f"{type(e).__name__}: {e}"

    t1 = perf_counter()
    result["detect_time"] = t1 - t0

    if result["detect_ok"]:
        try:
            bits = sample_qr_bits(image_gray, H, N_det)
            text = decode(bits)
            result["decode_ok"] = text == rec["payload"]
            result["text_det"] = text
            result["payload_gt"] = rec["payload"]
        except Exception as e:
            result["decode_ok"] = False
            result["decode_error"] = str(e)

    t2 = perf_counter()
    result["total_time"] = t2 - t0

    return result


def print_results(records: list[dict], results: list[dict]) -> None:
    N = len(results)
    n_detect = sum(r.get("detect_ok", False) for r in results)
    n_decode = sum(r.get("decode_ok", False) for r in results)
    n_version_ok = sum(r.get("version_ok", False) for r in results if r.get("detect_ok"))

    detect_rate = n_detect / N * 100 if N else 0
    decode_rate = n_decode / N * 100 if N else 0
    decode_of_detected = (
        n_decode / n_detect * 100 if n_detect else 0
    )
    version_accuracy = (
        n_version_ok / n_detect * 100 if n_detect else 0
    )

    print(f"\n{'=' * 60}")
    print(f"EVALUATION RESULTS ({N} samples)")
    print(f"{'=' * 60}")
    print(f"  Detection rate:      {n_detect}/{N} ({detect_rate:.1f}%)")
    print(f"  Decode rate:         {n_decode}/{N} ({decode_rate:.1f}%)")
    print(f"  Decode / detected:   {n_decode}/{n_detect} ({decode_of_detected:.1f}%)")
    print(f"  Version accuracy:    {n_version_ok}/{n_detect} ({version_accuracy:.1f}%)")

    corner_rmse = [r["corner_rmse"] for r in results if r.get("corner_rmse") is not None]
    corner_rmse_norm = [
        r["corner_rmse_norm"] for r in results if r.get("corner_rmse_norm") is not None
    ]
    if corner_rmse:
        print(f"\n  Corner RMSE (px):    {np.mean(corner_rmse):.2f} mean / {np.median(corner_rmse):.2f} median")
    if corner_rmse_norm:
        print(f"  Corner RMSE (mod):   {np.mean(corner_rmse_norm):.2f} mean / {np.median(corner_rmse_norm):.2f} median")

    detect_times = [r["detect_time"] for r in results if r.get("detect_ok")]
    if detect_times:
        print(f"\n  Detect time (ms):    {np.mean(detect_times)*1000:.0f} mean / {np.median(detect_times)*1000:.0f} median")

    errors = [r.get("error") for r in results if r.get("error") and not r.get("detect_ok")]
    if errors:
        print(f"\n  Detection failures ({len(errors)}):")
        from collections import Counter
        for msg, count in Counter(errors).most_common():
            print(f"    [{count:3d}] {msg}")

    decode_errors = [r.get("decode_error") for r in results if not r.get("decode_ok") and r.get("detect_ok")]
    if decode_errors:
        print(f"\n  Decode failures ({len(decode_errors)} detected-but-not-decoded):")
        from collections import Counter
        for msg, count in Counter(decode_errors).most_common(5):
            print(f"    [{count:3d}] {msg}")

    # Breakdown by version if ground truth available
    versions_gt = [rec["version"] for rec in records]
    unique_versions = sorted(set(versions_gt))
    if len(unique_versions) > 1:
        print(f"\n  By version:")
        for v in unique_versions:
            idx = [i for i, rec in enumerate(records) if rec["version"] == v]
            n_v = len(idx)
            n_det_v = sum(results[i].get("detect_ok", False) for i in idx)
            n_dec_v = sum(results[i].get("decode_ok", False) for i in idx)
            print(
                f"    V{v:2d}  detect {n_det_v}/{n_v} ({n_det_v/n_v*100:.0f}%)  "
                f"decode {n_dec_v}/{n_v} ({n_dec_v/n_v*100:.0f}%)"
            )


def main(argv: list[str] | None = None) -> None:
    parser = _build_parser()
    args = parser.parse_args(argv)

    dataset_dir = Path(args.dataset_dir)
    records = load_dataset(dataset_dir, num_samples=args.num_samples, seed=args.seed)

    print(f"Evaluating {len(records)} samples from {dataset_dir}")

    results: list[dict] = []
    for i, rec in enumerate(records):
        if i > 0 and i % 50 == 0:
            print(f"  {i}/{len(records)}...")
        results.append(evaluate_sample(rec, dataset_dir))

    print_results(records, results)


if __name__ == "__main__":
    main()
